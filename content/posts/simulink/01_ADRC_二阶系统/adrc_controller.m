function [u, v1, v2, z1, z2, z3] = adrc_controller(v, y, u_prev, v1, v2, z1, z2, z3, params)
% ADRC_CONTROLLER 完整 ADRC 控制器（对应论文式26）
%
% 包含三个模块：
%   1. TD  - 跟踪微分器（Tracking Differentiator）
%   2. ESO - 扩张状态观测器（Extended State Observer）
%   3. NLSEF - 非线性误差反馈（Nonlinear State Error Feedback）
%
% 输入：
%   v       - 给定值（设定点，可以是阶跃信号）
%   y       - 被控对象实际输出（反馈）
%   u_prev  - 上一时刻控制量（初始为 0，用于 ESO 更新）
%   v1,v2   - TD 状态（上一时刻，初始为 0）
%   z1,z2,z3- ESO 状态（上一时刻，初始为 0）
%   params  - 参数结构体（见下方说明）
%
% 输出：
%   u       - 控制量
%   v1,v2   - TD 状态（更新后，传入下一时刻）
%   z1,z2,z3- ESO 状态（更新后，传入下一时刻）
%
% params 字段：
%   params.h   - 采样周期
%   params.r0  - TD 加速度限幅
%   params.r   - NLSEF 加速度限幅
%   params.c   - NLSEF 阻尼系数（约为1）
%   params.h1  - NLSEF 精度系数（至少 4*h）
%   params.b0  - 被控对象增益估计
%   params.beta01 = 1
%   params.beta02 = 1/(2*h^0.5)
%   params.beta03 = 2/(25*h^1.2)

h      = params.h;
r0     = params.r0;
r      = params.r;
c      = params.c;
h1     = params.h1;
b0     = params.b0;
beta01 = params.beta01;
beta02 = params.beta02;
beta03 = params.beta03;

% =========================================================
% 模块一：TD 跟踪微分器
% 作用：软化给定值 v，输出平滑跟踪量 v1 和导数 v2
% 对应式(26)前两行
% =========================================================
fv = fhan(v1 - v, v2, r0, h);   % 时间最优控制量
v1 = v1 + h * v2;               % 更新跟踪值
v2 = v2 + h * fv;               % 更新跟踪导数

% =========================================================
% 模块二：ESO 扩张状态观测器
% 作用：估计系统状态 z1≈x1, z2≈x2，以及总扰动 z3≈f
% 对应式(26)中间部分（式22离散形式）
% =========================================================
e   = z1 - y;                          % 观测误差
fe  = fal(e, 0.5,  h);                 % 非线性校正项（中等强度）
fe1 = fal(e, 0.25, h);                 % 非线性校正项（温和，用于扰动估计）

z1 = z1 + h * z2           - beta01 * e;     % 更新状态1估计
z2 = z2 + h * (z3 + b0*u_prev) - beta02 * fe; % 更新状态2估计
z3 = z3                     - beta03 * fe1;   % 更新总扰动估计

% =========================================================
% 模块三：NLSEF 非线性误差反馈
% 作用：基于跟踪误差设计非线性控制律，消除扰动
% 对应式(26)最后两行
% =========================================================
e1 = v1 - z1;               % 位置误差
e2 = v2 - z2;               % 速度误差
u0 = fhan(e1, c*e2, r, h1); % 非线性反馈（fhan 提供时间最优收敛）
u  = -(u0 + z3) / b0;       % 补偿总扰动，得到最终控制量

end
